package drinksystem;

/**
 * Объединяет базовые напитки, декораторы (добавки) и меню в единую иерархию.
 * Благодаря этому меню и одиночный напиток обрабатываются одинаково (паттерн Composite).
 * Метод accept() подготовлен для двойной диспетчеризации (паттерн Visitor).
 */
public interface DrinkComponent {
    /**
     * Возвращает итоговую стоимость компонента.
     * Для меню суммирует цены всех вложенных элементов.
     */
    double getPrice();

    /**
     * Возвращает читаемое описание (название + добавки).
     */
    String getDescription();

    /**
     * Принимает объект-посетитель для выполнения операций над компонентом.
     * Позволяет добавлять новую логику (расчёт, печать, экспорт) без изменения классов.
     */
    void accept(MenuVisitor visitor);
}